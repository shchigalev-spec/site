export function resolveLandingData(key: RouteKey, url: URL) {
  const base = landingRoutes[key];
  const typeKey = key === 'general' ? url.searchParams.get('type') ?? '' : '';
  const typeVariant = typeVariants[typeKey];
  const regionVariant = regionVariants[url.searchParams.get('region') ?? ''];
  const requestedMode = url.searchParams.get('mode');
  const initialMode: DiagnosisMode = requestedMode === 'tender' || requestedMode === 'leasing' ? requestedMode : 'standard';
  const route = typeVariant ? { ...base, ...typeVariant } : base;
  const hasQuery = url.search.length > 0;

  return {
    route,
    canonical: `${publicSiteOrigin}${base.path}`,
    robots: hasQuery ? 'noindex,follow' : 'index,follow',
    regionLabel: regionVariant?.label ?? 'Россия / маршрут уточняем до расчёта',
    initialRegion: regionVariant?.id,
    initialObjectType: route.objectType,
    typeLabel: typeVariant?.typeLabel ?? '',
    initialMode,
    landingVariant: typeVariant ? `type:${typeKey}` : regionVariant ? `region:${url.searchParams.get('region')}` : key
  };
}
